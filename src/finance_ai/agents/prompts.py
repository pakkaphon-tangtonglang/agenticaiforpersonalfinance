from datetime import date


def get_date_context() -> str:
    """Return current date context string for system prompts.

    Returns:
        Thai date context string with today's date.

    Example:
        >>> get_date_context()
        'วันที่วันนี้: 2026-04-08\\n\\n'
    """
    return f"วันที่วันนี้: {date.today().isoformat()}\n\n"


