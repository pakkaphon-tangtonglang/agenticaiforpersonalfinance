def _format_bullets(items: list[str]) -> str:
    """Format items as prompt bullet lines.

    Args:
        items: Lines to bullet.

    Returns:
        Newline-joined '- item' lines, or '- (ไม่มี)' when empty.

    Example:
        >>> _format_bullets(["a", "b"])
        '- a\\n- b'
    """
    if not items:
        return "- (ไม่มี)"
    return "\n".join(f"- {item}" for item in items)


